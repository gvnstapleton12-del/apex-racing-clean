export function getCourseModifiers(course, archetype, distanceF = 0) {
  const profile = getCourseProfile(course)
  if (!profile.group || profile.group === 'UNKNOWN') return []
  const mods = []

  mods.push(`course_group_${profile.group.toLowerCase()}`)

  if (profile.handed === 'left') mods.push('course_hand_left')
  if (profile.handed === 'right') mods.push('course_hand_right')

  if (profile.uphill) mods.push('course_uphill_finish')

  if (profile.group === 'TIGHT_FLAT') {
    mods.push('course_tight_turn')
    if (distanceF > 0 && distanceF <= 6) {
      mods.push('tight_sprint')
    } else if (distanceF >= 10) {
      mods.push('tight_staying')
    }
  }

  if (profile.group === 'UNDULATING_FLAT') {
    if (distanceF > 0 && distanceF >= 10) {
      mods.push('undulating_stamina_test')
    }
  }

  if (profile.group === 'GALLOPING_FLAT' && distanceF > 0 && distanceF >= 10) {
    mods.push('galloping_stamina')
  }

  if (profile.specialistFactor >= 0.4) {
    mods.push('course_specialist')
  }

  if (profile.drawBias >= 0.6 && distanceF > 0 && distanceF <= 6) {
    mods.push('high_draw_bias_sprint')
  }

  if (profile.paceBias >= 0.6) {
    mods.push('pace_advantage_course')
  }

  return mods
}
