export function normalizeCourseName(course) {
  if (!course) return ''
  const c = course.toLowerCase().replace(/\s+/g, ' ').trim()
  const stripped = c.replace(/[^a-z]/g, '')
  // Multi-word course names
  if (c.includes('newmarket')) {
    return c.includes('july') ? 'newmarket_july' : 'newmarket_rowley'
  }
  if (c.includes('down royal') || stripped.includes('downroyal')) return 'down-royal'
  if (c.includes('market rasen') || c.includes('market_rasen') || stripped.includes('marketrasen')) return 'market-rasen'
  // Special hyphens
  const hyphenKey = COURSE_PROFILES[c.replace(/\s+/g, '-')]
  if (hyphenKey) return c.replace(/\s+/g, '-')
  // Fuzzy match
  for (const key of Object.keys(COURSE_PROFILES)) {
    if (stripped.includes(key) || key.includes(stripped)) return key
  }
  return stripped
}

export function getCourseProfile(course) {
  const key = normalizeCourseName(course)
  return COURSE_PROFILES[key] || { handed: 'unknown', type: 'unknown', uphill: false, group: 'UNKNOWN', drawBias: 0.3, paceBias: 0.4, staminaBias: 0.4, specialistFactor: 0.2 }
}

export function computeTrackCompatibility(noteCourse, raceCourse) {
  const noteProfile = getCourseProfile(noteCourse)
  const raceProfile = getCourseProfile(raceCourse)
  if (noteProfile.handed === 'unknown' || raceProfile.handed === 'unknown') return 1.0
  if (noteProfile.handed === raceProfile.handed) return 1.0
  return 0.5
}

